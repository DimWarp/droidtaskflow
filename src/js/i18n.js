function browserLang() {
    const b = ((typeof navigator !== 'undefined' && navigator.language) || 'en').toLowerCase();
    return b.startsWith('zh') ? 'zh' : 'en';
}

export function defaultLang() {
    return browserLang();
}

let _currentLang = defaultLang();

export function getLang() {
    return _currentLang;
}

export function t(key, params) {
    let v = i18n[_currentLang]?.[key];
    if (v == null) v = i18n.zh?.[key];
    if (v == null) return key;
    if (params && v.includes('{')) {
        return v.replace(/\{(\w+)\}/g, (m, name) =>
            params[name] != null ? String(params[name]) : m);
    }
    return v;
}

const _refreshHooks = [];
export function onLanguageChange(fn) {
    _refreshHooks.push(fn);
}

export function applyStaticDom(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

export function applyLanguage() {
    document.documentElement.setAttribute('lang', _currentLang === 'zh' ? 'zh-CN' : 'en');
    applyStaticDom();
    _refreshHooks.forEach(fn => {
        try { fn(); } catch (e) { console.warn('i18n refresh hook error:', e); }
    });
}

export function setLang(lang) {
    if (lang !== 'zh' && lang !== 'en') lang = 'zh';
    _currentLang = lang;
    const btn = document.getElementById('btnLang');
    // 按钮显示"将要切换到的语言"：中文界面显示 EN，英文界面显示 中。
    if (btn) btn.textContent = lang === 'zh' ? 'EN' : '中';
    applyLanguage();
}

export function toggleLang() {
    setLang(_currentLang === 'zh' ? 'en' : 'zh');
}
